/**
 * Opens a clean, print-ready window for the given report so the browser's
 * "Save as PDF" produces a real document. If the popup is blocked, falls back
 * to downloading the same markup as a standalone .html file.
 */
export function printReport(title: string, bodyHtml: string): void {
  const html = `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8" />
<title>${title}</title>
<style>
  body { font-family: Inter, Arial, sans-serif; color: #141b2b; margin: 32px; }
  h1 { font-size: 20px; margin: 0 0 4px; }
  .meta { color: #6b7280; font-size: 12px; margin-bottom: 20px; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
  th, td { text-align: left; padding: 8px 10px; border-bottom: 1px solid #e5e7eb; font-size: 12px; }
  th { background: #f3f4f6; text-transform: uppercase; letter-spacing: 0.04em; font-size: 11px; }
  .foot { margin-top: 28px; color: #6b7280; font-size: 11px; }
</style>
</head>
<body>
<h1>${title}</h1>
<div class="meta">Generated by VEMTAP • ${new Date().toLocaleString()}</div>
${bodyHtml}
<div class="foot">All financial figures reflect immutable ledger receipts. 0% VEMTAP commission on settled sales.</div>
</body>
</html>`;

  const win = window.open('', '_blank', 'width=900,height=700');
  if (win) {
    win.document.write(html);
    win.document.close();
    win.focus();
    // Give the window a beat to lay out before invoking the print dialog.
    window.setTimeout(() => win.print(), 250);
    return;
  }
  // Popup blocked — deliver the same document as a downloadable file.
  const blob = new Blob([html], { type: 'text/html;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', `${title.replace(/[^a-z0-9]+/gi, '_').toLowerCase()}.html`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/** Small helper to render a simple section of key/value rows for printReport. */
export function printKvTable(title: string, rows: Array<[string, string]>): string {
  return `<h2 style="font-size:14px;margin:0 0 8px;">${title}</h2>
<table><tbody>${rows.map(([k, v]) => `<tr><td>${k}</td><td>${v}</td></tr>`).join('')}</tbody></table>`;
}
